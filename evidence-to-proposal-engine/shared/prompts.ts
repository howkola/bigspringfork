function citationLine(c: Citation): string {
  return `[${c.id}] ${c.authors} (${c.year}). ${c.title}. ${c.source}. Finding: ${c.finding}`;
}

export function buildEvidenceContext(
  request: string,
  consensusCitations: Citation[]
): string {
  const anchorBlock = ANCHOR_LIBRARY.map(citationLine).join("\n");
  const consensusBlock = consensusCitations.map(citationLine).join("\n");

  return `You are a senior grants strategist for an NCA-accredited Children's Advocacy Center (Project Harmony, Omaha, Nebraska — serving eastern Nebraska and southwest Iowa, ~20 FTE, programs spanning forensic response, evidence-based treatment, family advocacy, prevention, a Training Institute, and Missing and Anti-Trafficking Youth Services).

FUNDING REQUEST:
"${request}"

EVIDENCE YOU MAY CITE — and the ONLY evidence you may cite:

== ANCHOR LIBRARY (cite as [A1]...[A11]) ==
${anchorBlock}

== CONSENSUS-RETRIEVED PEER-REVIEWED SOURCES (cite as [C1], [C2], ...) ==
${consensusBlock || "(none retrieved this run — rely on anchor library only)"}

CITATION INTEGRITY RULES (non-negotiable):
- Every empirical claim must carry an inline marker like [A2] or [C3].
- NEVER invent a citation, statistic, author, or year. If the evidence above does not support a claim, either omit it or write it as a program assertion without a citation marker.
- Do not cite anything not listed above.
- Local Omaha/Nebraska statistics: do NOT fabricate. Use placeholders like {{LOCAL: NE DHHS substantiated maltreatment count, most recent year}} so staff can insert verified local data.`;
}

export function buildSectionPrompt(
  evidenceContext: string,
  label: string,
  sectionKey: string
): string {
  return `${evidenceContext}

TASK: Write ONLY the "${label}" section of the evidence packet.
Section brief: ${SECTION_SPECS[sectionKey]}

Constraints:
- Respond with the raw markdown of this one section and NOTHING else — no JSON, no code fences, no preamble like "Here is...", no closing commentary, no top-level title (the UI supplies the section heading).
- Keep it under ~550 words so it completes within the response limit.
- Use the inline citation markers and {{LOCAL: ...}} placeholders per the rules above.`;
}
