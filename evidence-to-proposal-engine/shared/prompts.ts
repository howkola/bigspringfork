import type { Citation } from "./types";
import { ANCHOR_LIBRARY } from "./anchors";

/* ---------- Prompts ----------
   These are server-side only (imported by the Netlify functions), but live in
   shared/ so the anchor library stays a single source of truth. */

export function buildConsensusPrompt(request: string): string {
  return `You are the evidence-retrieval stage of a grant research pipeline for an NCA-accredited Children's Advocacy Center.

Funding request under development:
"${request}"

Use the Consensus search tool to find peer-reviewed evidence supporting this request. Run focused searches on:
1. Children's Advocacy Center model effectiveness / multidisciplinary team response to child abuse
2. Trauma screening for maltreated children (validity, outcomes)
3. Family advocacy / caregiver support and engagement in child abuse cases
4. Identification and response to child sex trafficking / commercial sexual exploitation
5. Outcomes of coordinated investigation (reduced interviews, prosecution, service linkage)

After searching, list every relevant peer-reviewed paper you found. For each: authors, year, title, journal, DOI or URL if available, and a one-sentence finding relevant to this request. Only list papers actually returned by the search tool — do not add papers from memory.`;
}

export function buildStructuringPrompt(rawSearchOutput: string): string {
  return `Below is raw output from a peer-reviewed literature search. Extract ONLY papers explicitly present in this text. Respond with ONLY a JSON object: {"citations":[{"id":"C1","authors":"...","year":"...","title":"...","source":"journal + DOI/URL if present","finding":"one-sentence relevant finding"}]}. Number sequentially C1, C2, ... Maximum 8 citations, and keep every field under 25 words so the full JSON stays short. If no clearly identifiable papers, return {"citations":[]}.

=== RAW SEARCH OUTPUT ===
${rawSearchOutput.slice(0, 9000)}`;
}

